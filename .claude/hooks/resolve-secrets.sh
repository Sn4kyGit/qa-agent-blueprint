#
# resolve-secrets.sh — resolves the test-user secrets a project DECLARES (via
# "Secrets source: keychain" in PROJECT.md / PRODUCT.md) into
# .env.playwright-secrets, the file the playwright MCP server reads via
# --secrets (values masked in tool responses). Projects without the field are
# "env-file": the user fills the file by hand — the original behavior,
# untouched by this script.
#
# Keychain convention (macOS): service name = secret key, account free.
# Store once, e.g.:
#   security add-generic-password -s SHOP_QA_STANDARD_PASSWORD -a qa -w
#
# Output discipline (hard rule): this script NEVER prints a resolved value —
# stdout is key names + status only. That is what makes it safe for the agent
# to run directly: the guard blocks agent WRITES to .env*, but this script
# only (re)generates the canonical, gitignored, chmod-600 file whose values
# the MCP server masks anyway. Nothing here routes a value into a transcript.
#
# Modes:
#   resolve-secrets.sh [CWD]           resolve + merge into .env.playwright-secrets
#   resolve-secrets.sh [CWD] --status  no keychain access, no writes — report which
#                                      declared keys are present in the file
#                                      (one compact line; silent when no project
#                                      declares keychain)
#   resolve-secrets.sh [CWD] --import  migrate values the file ALREADY holds (e.g.
#                                      hand-filled env-file mode) into the keychain.
#                                      Declared keys only — the script never sweeps
#                                      arbitrary file lines into the vault. Values
#                                      travel via stdin (never argv, never stdout).
#                                      Existing keychain items are kept; --force
#                                      overwrites (-U).
#   resolve-secrets.sh [CWD] --capture ask the human for each missing key through a
#                                      native macOS hidden-answer dialog and store
#                                      it straight into the keychain — the user
#                                      types into a GUI box, never into the chat,
#                                      so the value never enters the transcript.
#                                      Headless (no GUI): prints the manual
#                                      one-time commands instead. Ends by resolving
#                                      so the file reflects the new state.
#   Any mode accepts --force as 2nd/3rd argument where meaningful.
#
# Merge semantics: everything between the managed-block markers is regenerated
# from the current declarations; user lines outside the block are preserved
# verbatim. A key that fails to resolve (missing/locked keychain) KEEPS its
# previously resolved value if one exists — a locked keychain must never
# downgrade the file. Missing keys are reported with the exact one-time
# `security add-generic-password` command, never as a hard failure.
#
# Exit 0 always — secrets resolution is a convenience layer; a missing key is
# a report, never a reason to fail a session start.
#
set -uo pipefail

CWD="${1:-$PWD}"
MODE="resolve"; FORCE=0
for arg in "${@:2}"; do
  case "$arg" in
    --status|--import|--capture) MODE="${arg#--}" ;;
    --force) FORCE=1 ;;
  esac
done

if ! command -v python3 >/dev/null 2>&1; then
  # Declaration parsing is python-based (same dependency as the other hooks).
  # Without it: stay silent in status mode, say so in resolve mode.
  [ "$MODE" = "resolve" ] && \
    echo "resolve-secrets: python3 not found — cannot parse project declarations." >&2
  exit 0
fi

python3 - "$CWD" "$MODE" "$FORCE" <<'PY'
import os, re, subprocess, sys

cwd, mode, force = sys.argv[1], sys.argv[2], sys.argv[3] == "1"
SECRETS_FILE = os.path.join(cwd, ".env.playwright-secrets")
BLOCK_START = "# --- qa-blueprint managed block (resolve-secrets.sh) ---"
BLOCK_END = "# --- end qa-blueprint managed block ---"
HEADER = ("# Secrets consumed by Playwright MCP via --secrets (values are masked in tool\n"
          "# responses, so the agent never sees them). Gitignored — never commit.\n"
          "# Reference per-project test users by the keys used in projects/<KEY>/PROJECT.md.\n"
          "# Lines between the managed-block markers are regenerated by the blueprint's\n"
          "# resolve-secrets.sh from each project's declared `Secrets source`;\n"
          "# everything outside the block is yours.\n")

TOKEN_RE = re.compile(r'[A-Z][A-Z0-9]+(?:_[A-Z0-9]+)+')

def declared_source(text):
    m = re.search(r'\*\*Secrets source\*\*:\s*`?([A-Za-z-]+)`?', text)
    return m.group(1).lower() if m else None

def section(text, name):
    m = re.search(r'^## ' + re.escape(name) + r'\b(.*?)(?=^## |\Z)', text, re.S | re.M)
    return m.group(1) if m else ""

def keys_in(text):
    out = []
    for line in text.splitlines():
        for m in TOKEN_RE.finditer(line):
            i = m.start()
            # Skip placeholder suffixes like <KEY>_QA_STANDARD_PASSWORD: the match
            # starts right after '<' (or continues one started after '_').
            if i > 0 and line[i - 1] in '<_':
                continue
            tok = m.group(0)
            if tok not in out:
                out.append(tok)
    return out

def file_keys(path):
    try:
        text = open(path, encoding="utf-8").read()
    except Exception:
        return [], None
    keys = keys_in(section(text, "Test users"))
    for line in text.splitlines():
        if "JIRA login" in line:
            for k in keys_in(line):
                if k not in keys:
                    keys.append(k)
    return keys, declared_source(text)

# Collect key -> effective source across all onboarded projects. Product files
# override the project's source only when they declare one themselves.
key_source = {}
projects_dir = os.path.join(cwd, "projects")
if os.path.isdir(projects_dir):
    for pkey in sorted(os.listdir(projects_dir)):
        if pkey in ("_template", "EXAMPLE"):
            continue
        pdir = os.path.join(projects_dir, pkey)
        if not os.path.isdir(pdir):
            continue
        pkeys, psrc = file_keys(os.path.join(pdir, "PROJECT.md"))
        psrc = psrc or "env-file"
        for k in pkeys:
            key_source.setdefault(k, psrc)
        prods = os.path.join(pdir, "products")
        if os.path.isdir(prods):
            for prod in sorted(os.listdir(prods)):
                if prod == "_template":
                    continue
                f = os.path.join(prods, prod, "PRODUCT.md")
                if not os.path.isfile(f):
                    continue
                kkeys, ksrc = file_keys(f)
                for k in kkeys:
                    key_source.setdefault(k, ksrc or psrc)

all_keys = sorted(key_source.keys())
keychain_keys = sorted(k for k, s in key_source.items() if s == "keychain")
if not all_keys:
    sys.exit(0)  # no declared keys at all — stay silent

def read_file():
    try:
        return open(SECRETS_FILE, encoding="utf-8").read()
    except Exception:
        return None

def present_keys(text):
    found = set()
    if text:
        for line in text.splitlines():
            m = re.match(r'^([A-Z][A-Z0-9_]+)=', line)
            if m:
                found.add(m.group(1))
    return found

if mode == "status":
    # 0.19.8: report ALL declared keys (keychain + env-file), not just keychain.
    # This is the sanctioned existence channel — names only, never values.
    have = present_keys(read_file())
    missing = [k for k in all_keys if k not in have]
    if missing:
        print("declared keys: %d/%d present in .env.playwright-secrets — missing: %s "
              "(resolve: run the blueprint's resolve-secrets.sh, or fill the file)"
              % (len(all_keys) - len(missing), len(all_keys), ", ".join(missing)))
    else:
        print("declared keys: %d/%d present in .env.playwright-secrets"
              % (len(all_keys), len(all_keys)))
    sys.exit(0)

# --- shared keychain helpers (import/capture/resolve) -------------------------
def have_security():
    return subprocess.call(["which", "security"],
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL) == 0

def keychain_has(k):
    return subprocess.run(["security", "find-generic-password", "-s", k, "-w"],
                          capture_output=True).returncode == 0

def keychain_store(k, v):
    # -w as the LAST argument (no value after it) reads the password from stdin
    # (twice: confirmation) — anything following -w is taken AS the password,
    # so -U must come before it. The value travels via stdin: never argv
    # (visible in ps), never stdout (captured into the transcript).
    args = ["security", "add-generic-password", "-s", k, "-a", "qa", "-U", "-w"]
    r = subprocess.run(args, input=v + "\n" + v + "\n", text=True, capture_output=True)
    return r.returncode == 0

def file_values(text):
    vals = {}
    if text:
        for line in text.splitlines():
            m = re.match(r'^([A-Z][A-Z0-9_]+)=(.*)$', line)
            if m and m.group(1) not in vals:
                vals[m.group(1)] = m.group(2)
    return vals

def manual_hint(k):
    return "  store manually: security add-generic-password -s %s -a qa -w" % k

# --- import mode: file -> keychain, declared keys only ------------------------
if mode == "import":
    if not have_security():
        print("resolve-secrets --import: the macOS `security` CLI is unavailable here.")
        sys.exit(0)
    values = file_values(read_file())
    imported, skipped, not_in_file, failed = [], [], [], []
    for k in keychain_keys:
        if k not in values:
            not_in_file.append(k)
            continue
        if keychain_has(k) and not force:
            skipped.append(k)
            continue
        (imported if keychain_store(k, values[k]) else failed).append(k)
    if keychain_keys:
        print("resolve-secrets --import: %d stored in keychain%s%s%s"
              % (len(imported),
                 ", %d already present (skipped — --force overwrites)" % len(skipped) if skipped else "",
                 ", %d declared but not in the file" % len(not_in_file) if not_in_file else "",
                 ", %d FAILED" % len(failed) if failed else ""))
    else:
        print("resolve-secrets --import: no vault-sourced keys — env-file mode, nothing to import.")
    for k in imported:
        print("  stored %s" % k)
    for k in not_in_file + failed:
        print(manual_hint(k))
    sys.exit(0)

# --- capture mode: GUI hidden-answer dialog -> keychain, then resolve ---------
if mode == "capture":
    if not have_security() or subprocess.call(
            ["which", "osascript"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL) != 0:
        print("resolve-secrets --capture: needs macOS (`security` + `osascript`); "
              "store the keys manually instead:")
        for k in keychain_keys:
            print(manual_hint(k))
        sys.exit(0)
    targets = [k for k in keychain_keys if force or not keychain_has(k)]
    if not targets:
        if keychain_keys:
            print("resolve-secrets --capture: all declared keys are already in the keychain.")
        else:
            print("resolve-secrets --capture: no vault-sourced keys — env-file mode, fill .env.playwright-secrets manually.")
    stored, skipped = [], []
    for k in targets:
        dialog = ('display dialog "Password for %s (account: qa) — stored directly into '
                  'the macOS Keychain, never into the chat." default answer "" '
                  'with hidden answer with title "QA Blueprint Keychain" '
                  'buttons {"Cancel", "Store"} default button "Store"') % k
        r = subprocess.run(["osascript", "-e", dialog], capture_output=True, text=True)
        if r.returncode != 0:
            skipped.append(k)  # Cancel or no GUI (headless)
            continue
        m = re.search(r'text returned:(.*)$', r.stdout)
        v = (m.group(1) if m else "").strip()
        if not v:
            skipped.append(k)
            continue
        (stored if keychain_store(k, v) else skipped).append(k)
        v = None
    if stored:
        print("resolve-secrets --capture: stored %s" % ", ".join(stored))
    for k in skipped:
        print(manual_hint(k))
    # fall through into resolve so the file reflects the new keychain state

# --- resolve mode -------------------------------------------------------------
if not have_security():
    print("resolve-secrets: projects declare `Secrets source: keychain` but the macOS "
          "`security` CLI is unavailable here — fill .env.playwright-secrets by hand "
          "or switch the project's source to env-file.")
    sys.exit(0)

resolved, missing = {}, []
for k in keychain_keys:
    r = subprocess.run(["security", "find-generic-password", "-s", k, "-w"],
                       capture_output=True, text=True)
    if r.returncode == 0 and r.stdout.strip():
        resolved[k] = r.stdout.strip()
    else:
        missing.append(k)

text = read_file()
before, old_block, after = [], [], []
if text is None:
    before = [HEADER]
else:
    state = "before"
    for ln in text.splitlines(keepends=True):
        if state == "before" and ln.strip() == BLOCK_START:
            state = "block"; continue
        if state == "block" and ln.strip() == BLOCK_END:
            state = "after"; continue
        (before if state == "before" else old_block if state == "block" else after).append(ln)

old_values = {}
for ln in old_block:
    m = re.match(r'^([A-Z][A-Z0-9_]+)=(.*)$', ln.rstrip("\n"))
    if m:
        old_values[m.group(1)] = m.group(2)

kept = 0
block_lines = [BLOCK_START + "\n"]
for k in keychain_keys:
    if k in resolved:
        block_lines.append("%s=%s\n" % (k, resolved[k]))
    elif k in old_values:
        block_lines.append("%s=%s\n" % (k, old_values[k]))
        kept += 1
block_lines.append(BLOCK_END + "\n")

body = "".join(before)
if body and not body.endswith("\n"):
    body += "\n"
body += "".join(block_lines) + "".join(after)

try:
    fd = os.open(SECRETS_FILE, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(body)
    os.chmod(SECRETS_FILE, 0o600)
except Exception as e:
    print("resolve-secrets: cannot write %s: %s" % (SECRETS_FILE, e), file=sys.stderr)
    sys.exit(0)

print("resolve-secrets: %d/%d keys resolved into .env.playwright-secrets%s"
      % (len(resolved), len(keychain_keys),
         " (%d kept from previous run)" % kept if kept else ""))
for k in missing:
    print("  MISSING %s — store once: security add-generic-password -s %s -a qa -w" % (k, k))
PY
exit 0
